// Automatic SEO for the built site (runs after every `npm run build`, see package.json "postbuild").
// From seo/site.json + the real level data it:
//  - writes title, description, canonical, robots, Open Graph, Twitter card, verification tags and
//    JSON-LD (VideoGame, WebSite, FAQPage, VideoObject, BreadcrumbList, DefinedTermSet) into every page
//  - generates one page per level (story, real screenshot, Pidgin lines with English) and a Pidgin glossary
//  - writes sitemap.xml (with images and git-based lastmod), 404.html and the IndexNow key file
//  - validates the result and FAILS the build on broken links, missing images, bad lengths,
//    duplicate titles, invalid JSON-LD, or "no ads" claims in a build that has ads/payments switched on.
// Usage: node --experimental-strip-types scripts/seo.mjs [--check]   (--check = validate only)
import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = resolve(fileURLToPath(import.meta.url), '../..');
const DIST = join(ROOT, 'dist');
const SITE = JSON.parse(readFileSync(join(ROOT, 'seo', 'site.json'), 'utf8'));
const URL0 = SITE.siteUrl;
const abs = (p) => new URL(p === 'index.html' ? '' : p, URL0).href;

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
/** Trim to a search-snippet-sized description (≤160 chars) at a word boundary. */
const fit = (s, n = 160) => (s.length <= n ? s : s.slice(0, n - 1).replace(/\s+\S*$/, '') + '…');
export const slug =(s) => s.toLowerCase().normalize('NFKD').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

/** Last git commit date (YYYY-MM-DD) touching any of these paths; today if uncommitted/unknown. */
function lastmod(...paths) {
  try {
    const d = execFileSync('git', ['log', '-1', '--format=%cs', '--', ...paths], { cwd: ROOT, encoding: 'utf8' }).trim();
    const dirty = execFileSync('git', ['status', '--porcelain', '--', ...paths], { cwd: ROOT, encoding: 'utf8' }).trim();
    if (d && !dirty) return d;
  } catch { /* not a git checkout */ }
  return new Date().toISOString().slice(0, 10);
}

// ───────────── Level data: titles from the game itself, lines pulled from the level scripts ─────────────

async function loadLevels() {
  const { LEVELS } = await import(pathToFileURL(join(ROOT, 'src', 'story', 'levels.ts')).href);
  const src = readFileSync(join(ROOT, 'src', 'story', 'levels.ts'), 'utf8');
  const starts = LEVELS.map((l) => src.indexOf(`n: ${l.n}, title:`));
  const STR = String.raw`'((?:\\.|[^'\\])*)'`;
  const unq = (s) => s.replace(/\\(.)/g, '$1');
  return LEVELS.map((l, i) => {
    const body = src.slice(starts[i], starts[i + 1] > 0 ? starts[i + 1] : undefined);
    // Lines appear as { who, text, plain } objects, g.say(who, text, plain), g.banner(text, plain) and NARR(text, plain).
    const found = [];
    const add = (re, f) => { for (const m of body.matchAll(re)) found.push({ at: m.index, ...f(m) }); };
    add(new RegExp(String.raw`who: '(\w+)', text: ${STR}, plain: ${STR}`, 'g'), (m) => ({ who: m[1], text: m[2], plain: m[3] }));
    add(new RegExp(String.raw`g\.say\('(\w+)', ${STR}, ${STR}\)`, 'g'), (m) => ({ who: m[1], text: m[2], plain: m[3] }));
    add(new RegExp(String.raw`(?:g\.banner|NARR)\(${STR}, ${STR}\)`, 'g'), (m) => ({ who: 'narrator', text: m[1], plain: m[2] }));
    const lines = found.sort((a, b) => a.at - b.at).map((x) => ({ who: x.who, text: unq(x.text), plain: unq(x.plain) }));
    const extra = SITE.levels[l.n] ?? {};
    return { n: l.n, title: l.title, plain: l.plain, emoji: l.emoji, teaser: l.teaser, win: l.win, lines, ...extra, file: `${slug(l.title)}.html`, image: `media/og/level-${l.n}.jpg` };
  });
}

