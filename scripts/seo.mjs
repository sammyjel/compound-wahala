// ───────────── Validation ─────────────

export function validate(dir = DIST) {
  const errs = [];
  const files = readdirSync(dir).filter((f) => f.endsWith('.html'));
  const seen = { title: new Map(), description: new Map() };
  const adsOn = !!process.env.VITE_ADS_PROVIDER || process.env.VITE_PAYMENTS === 'on';
  for (const f of files) {
    const html = readFileSync(join(dir, f), 'utf8');
    const get = (re) => html.match(re)?.[1];
    const title = get(/<title>([^<]*)<\/title>/);
    const desc = get(/<meta name="description" content="([^"]*)"/);
    const canon = get(/<link rel="canonical" href="([^"]*)"/);
    const noindex = /<meta name="robots" content="noindex/.test(html);
    if (!title) errs.push(`${f}: no <title>`);
    else if (title.length > 70) errs.push(`${f}: title ${title.length} chars (max 70): ${title}`);
    if (!desc) errs.push(`${f}: no meta description`);
    else if (desc.length < 50 || desc.length > 170) errs.push(`${f}: description ${desc.length} chars (50-170)`);
    if ((html.match(/<title>/g) ?? []).length > 1) errs.push(`${f}: more than one <title>`);
    if (canon !== abs(f)) errs.push(`${f}: canonical ${canon} should be ${abs(f)}`);
    if (!noindex) for (const k of ['title', 'description']) {
      const v = k === 'title' ? title : desc;
      if (seen[k].has(v)) errs.push(`${f}: duplicate ${k} with ${seen[k].get(v)}`); else seen[k].set(v, f);
    }
    for (const m of html.matchAll(/<meta (?:property|name)="(?:og|twitter):image" content="([^"]*)"/g)) {
      if (!m[1].startsWith(URL0)) errs.push(`${f}: social image not absolute: ${m[1]}`);
      else if (!existsSync(join(dir, m[1].slice(URL0.length)))) errs.push(`${f}: social image missing: ${m[1]}`);
    }
    for (const m of html.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/g)) {
      try { JSON.parse(m[1]); } catch (e) { errs.push(`${f}: invalid JSON-LD (${e.message})`); }
    }
    // Every relative link/image on the page must exist in the build.
    for (const m of html.matchAll(/\s(?:href|src|poster)="([^"#?]+)[^"]*"/g)) {
      const u = m[1];
      if (/^(https?:|mailto:|data:|javascript:|\/\/)/.test(u) || u === './') continue;
      if (!existsSync(join(dir, u))) errs.push(`${f}: broken link ${u}`);
    }
    if (adsOn && /no ads|nothing to buy|no purchases/i.test(html)) errs.push(`${f}: says "no ads/purchases" but this build has ads or payments ON — update the copy`);
  }
  const sm = existsSync(join(dir, 'sitemap.xml')) ? readFileSync(join(dir, 'sitemap.xml'), 'utf8') : '';
  if (!sm) errs.push('sitemap.xml missing');
  for (const m of sm.matchAll(/<loc>([^<]*)<\/loc>/g)) {
    const p = m[1].slice(URL0.length) || 'index.html';
    if (!m[1].startsWith(URL0) || !existsSync(join(dir, p))) errs.push(`sitemap: ${m[1]} not in build`);
  }
  return { ok: !errs.length, errs, pages: files.length };
}

// ───────────── Main ─────────────

async function build() {
  if (!existsSync(join(DIST, 'index.html'))) throw new Error('dist/ not built — run npm run build');
  const levels = await loadLevels();
  for (const l of levels) {
    if (!l.story) throw new Error(`seo/site.json: levels.${l.n} missing (story, skills, fact)`);
    if (!existsSync(join(ROOT, 'public', l.image))) throw new Error(`${l.image} missing — run npm run seo:shots`);
  }
  const lvlSrc = ['src/story/levels.ts', 'seo/site.json'];
  const entries = [];

  for (const f of ['index.html', 'home.html', 'privacy.html', 'feedback.html']) {
    const p = SITE.pages[f];
    const fp = join(DIST, f);
    let html = readFileSync(fp, 'utf8');
    let jsonld = [];
    if (f === 'index.html') {
      jsonld = [game(), { '@type': 'WebSite', '@id': `${URL0}#site`, name: SITE.name, url: URL0, inLanguage: 'en' }];
      html = html.replace(/<noscript>[\s\S]*?<\/noscript>\s*/i, '').replace(/<body>/i, `<body>\n${noscript(levels)}`);
    }
    if (f === 'home.html') {
      jsonld = [
        game(),
        { '@type': 'FAQPage', mainEntity: SITE.faq.map((q) => ({ '@type': 'Question', name: q.q, acceptedAnswer: { '@type': 'Answer', text: q.a } })) },
        { '@type': 'VideoObject', name: `${SITE.name} — gameplay trailer`, description: 'Real gameplay from Compound Wahala Story Mode.', thumbnailUrl: abs('media/trailer-poster.jpg'), contentUrl: abs('media/trailer.mp4'), uploadDate: '2026-10-14', isFamilyFriendly: true },
      ];
      html = html.replace(/<!-- seo:faq -->[\s\S]*?<!-- \/seo:faq -->/, '').replace(/<section class="band">/, `${faqHtml()}\n\n<section class="band">`);
    }
    html = injectHead(html, head({ file: f, title: p.title, description: p.description, image: p.image, imageAlt: p.imageAlt, jsonld }));
    writeFileSync(fp, html);
    entries.push({ file: f, priority: p.priority, lastmod: lastmod(f === 'index.html' ? 'src' : `public/${f}`, 'seo/site.json'), images: f === 'index.html' ? [p.image] : f === 'home.html' ? ['media/og/title.jpg', 'media/og/map.jpg'] : [] });
  }

  for (const l of levels) {
    const pg = levelPage(l, levels);
    writeFileSync(join(DIST, pg.file), pg.html);
    entries.push({ file: pg.file, priority: '0.8', lastmod: lastmod(...lvlSrc, `public/${l.image}`), images: [l.image] });
  }
  const g = glossaryPage(levels);
  writeFileSync(join(DIST, g.file), g.html);
  entries.push({ file: g.file, priority: SITE.pages['pidgin.html'].priority, lastmod: lastmod(...lvlSrc) });

  writeFileSync(join(DIST, '404.html'), notFound());
  writeFileSync(join(DIST, 'sitemap.xml'), sitemap(entries));
  const key = readFileSync(join(ROOT, 'seo', 'indexnow-key.txt'), 'utf8').trim();
  writeFileSync(join(DIST, `${key}.txt`), key);
  return entries.length;
}

